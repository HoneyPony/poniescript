	pub fn put_sig(&mut self, sig: &Sig) -> SigId {
		if let Some(existing) = self.sig_side_map.get(sig) {
			return *existing;
		}

		let id = self.push(sig.clone());

		self.sig_side_map.insert(sig.clone(), id);

		id
	}

