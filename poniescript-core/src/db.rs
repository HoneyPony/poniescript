	/// Computes the number of slots that the given type needs if a value of
	/// it is stored.
	/// 
	/// Every value in the type that needs a slot must be stored to the GC
	/// shadow stack at any time that the current thread might be doing a stack
	/// scan.
	pub fn type_gc_slots(&self, id: TypId) -> usize {
		match self.get(id) {
			Type::Int | Type::Float | Type::Bool => 0,
			Type::Void => 0,

			Type::StrConst => 0,
			Type::Str => 1,
			Type::StrBuf => 1,

			Type::FunRaw(_) => 0,
			Type::Fun(_) => 1,

			Type::Bottom => 0,
			Type::Class(_) => 1,
			Type::ArrayOf(_) => 1,
			Type::Tuple(typ_ids) => {
				// TODO: Given that we have to call this function for every
				// single tuple Val that we create, we really should probably
				// cache this values.
				let mut sum = 0;
				for typ in typ_ids.iter() {
					sum += self.type_gc_slots(*typ);
				}
				sum
			},
			Type::Option(id) => {
				// It should require the same number of slots as its inner type
				self.type_gc_slots(*id)
			}
			Type::Unassigned => 0,
			Type::AssumeInt => 0,
			Type::AssumeFloat => 0,
			Type::UnboundIdent(_) => 0,
			Type::UnboundCStructPtr(_) => 0,
		}
	}
	
	pub fn lookup_property(&self, typ: TypId, propname: StrId) -> Option<VarId> {
		let ty = self.get(typ);
		match ty {
			// HACK: Right now these all do the same thing.
			Type::Str | Type::StrConst | Type::StrBuf => {
				if propname == self.prop_str.length_key {
					return Some(self.prop_str.length);
				}

				None
			},
			Type::ArrayOf(_) => {
				if propname == self.prop_array.length_key {
					return Some(self.prop_array.length);
				}

				None
			}
			Type::Class(class_id) => {
				let class = self.get(*class_id);
				let result = class.var_map.get(&propname).copied();
				result
			},
			Type::Tuple(typs) => {
				// Look up the property index based on name ('0' => 0)
				let Some(which_prop) = self.tuple_idxs.get(&propname) else { return None; };

				// We have to manually check the index, this is how we know
				// whether properties are available.
				if (*which_prop as usize) >= typs.len() {
					return None;
				}

				// Now look up the variable based on index-type pair. This should
				// have been generated the first time we used the type.
				self.tuple_vars.get(&(*which_prop, typs[*which_prop as usize])).copied()
			}

			_ => None
		}
	}

