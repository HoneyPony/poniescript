	pub fn synthesize_property(&mut self, str: &str, cname: &'static str, typ: TypId) -> (StrId, VarId) {
		let key = self.put_str(str);
		let var = Var {
			name: key,
			typ,
			fun: None,
			class: None,
			init: false,
			initializer: None,
			location: self.synthetic(),
		};
		let var = self.push(var);

		self.known_var_cnames.insert(var, cname);

		(key, var)
	}

