	fn visit_value_types(&mut self, todo: &mut FxHashSet<TypId>, visited: &mut FxHashSet<TypId>, ordering: &mut Vec<TypId>, typ: TypId) -> Result<(), ()> {
		// Only visit types that still need to be visited.
		if !todo.contains(&typ) {
			return Ok(());
		}

		// If this type was already in the visisted set, that means we have
		// a cycle.
		if !visited.insert(typ) {
			// TODO: Figure out how to get source information
			self.report_error(Error::simple("Cycle in value types".into(), self.synthetic()));
			return Err(());
		}

		// Visit child types.
		match self.get(typ) {
			Type::Tuple(typ_ids) => {
				// TODO: Why. Please. Help
				let typ_ids_clone = typ_ids.clone();

				for inner in typ_ids_clone.iter() {
					self.visit_value_types(todo, visited, ordering, *inner)?;
				}
			},
			// Nothing to visit. Yet.
			_ => {}
		}

		// We are now no longer in the todo set, and we shouldn't be in the
		// visisted set anymore as other types are allowed to see us.
		todo.remove(&typ);
		visited.remove(&typ);

		// Push ourselves to the ordering now, because our children should all
		// be there before us.
		ordering.push(typ);

		Ok(())
	}
	
	pub fn sort_value_types(&mut self) -> Result<(), ()> {
		let mut visited: FxHashSet<TypId> = FxHashSet::default();
		let mut todo: FxHashSet<TypId> = FxHashSet::default();
		let mut ordering: Vec<TypId> = Vec::new();

		for ty in &self.value_types {
			todo.insert(*ty);
		}

		// Take value types so we can iterate over them without the borrow
		// checker complaining.
		let old = std::mem::take(&mut self.value_types);

		for ty in old {
			self.visit_value_types(&mut todo, &mut visited, &mut ordering, ty)?;
		}

		// Now they are in a safe order.
		self.value_types = ordering;

		Ok(())
	}

	fn generate_tags(&mut self) {
		// Start at a somewhat high value so we don't have to update this wrt
		// the standard library too much. We still have to figure out how to
		// import existing tags, of course.
		let mut tag_num = 256u64;
		for typ in self.iter_typ() {
			if !self.is_cgen_safe(typ) { continue; }

			match self.get(typ) {
				Type::Int => { self.tag_cname_cache.insert(typ, "PONI_TAG_INT"); }
				Type::Float => { self.tag_cname_cache.insert(typ, "PONI_TAG_FLOAT"); }
				Type::Bool => { self.tag_cname_cache.insert(typ, "PONI_TAG_BOOL"); }

				Type::Str => { self.tag_cname_cache.insert(typ, "PONI_TAG_STR"); }
				Type::StrBuf => { self.tag_cname_cache.insert(typ, "PONI_TAG_STRBUF"); }
				Type::StrConst => { self.tag_cname_cache.insert(typ, "PONI_TAG_STRCONST"); }
			
				// No tag, as there is no way (?) to store a value of these types.
				Type::Void | Type::Bottom => continue,

				// All arrays use the same tag.
				Type::ArrayOf(_) => { self.tag_cname_cache.insert(typ, "PONI_TAG_ARRAY"); },

				Type::Fun(_) | Type::Class(_) => {
					// This is very sad, but for now we'll just make their name
					// the TypId. We really should make it some kind of relevant
					// string instead.
					let name = format!("PONI_TAG_TY{}", typ.to_nonzero_usize());
					writeln!(self.tag_define_code, "#define {name} 0x{tag_num:x}ULL").unwrap();
					tag_num += 2; // For now, the GC bit is the last bit. This
					// might change.	
					
					self.tag_cname_cache.insert(typ, name.leak());
				}
				Type::FunRaw(_) | Type::Tuple(_) => {
					// This is very sad, but for now we'll just make their name
					// the TypId. We really should make it some kind of relevant
					// string instead.
					let name = format!("PONI_TAG_TY{}", typ.to_nonzero_usize());
					// For now, we'll make value types simply have their high bit
					// set, so we can easily distinguish them.
					writeln!(self.tag_define_code, "#define {name} 0x{:x}ULL", tag_num | 0x8000000000000000).unwrap();
					tag_num += 2; // For now, the GC bit is the last bit. This
					// might change.	
					
					self.tag_cname_cache.insert(typ, name.leak());

				}
				Type::Option(id) => {
					// Because nullable types are the same type, we reuse
					// the tag. (?)
					//
					// For value types, we require a new tag.
					if self.is_value_type(*id) {
						// For now, just do nothing...
						//todo!()
					}
					else {
						let name = format!("PONI_TAG_TY{}", typ.to_nonzero_usize());
						// Generate the macro in terms of the other one (?)
						writeln!(self.tag_define_code, "#define {name} PONI_TAG_TY{}", id.to_nonzero_usize()).unwrap();
						tag_num += 2; // For now, the GC bit is the last bit. This
						// might change.	
						
						self.tag_cname_cache.insert(typ, name.leak());
					}
				}
				Type::Unassigned | Type::AssumeInt | Type::AssumeFloat | Type::UnboundIdent(_) | Type::UnboundCStructPtr(_) => continue,
			}
		}
	}

